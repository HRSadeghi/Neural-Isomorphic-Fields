"""Table A.4 and the macros of the length analyses (runs/<run>/lengths_parts.json, written by
analysis/parts.py), used by make_tables.py.

A test number is "within the training lengths" if its integer part and its fractional part have at most
max_part_trained digits (the range of the uniform half of the training numbers: 12 for N = 25, N/2 otherwise);
"longer part" means a number of D_N with a longer part; "more than N digits" means a number outside D_N.
"""
from __future__ import annotations

import json
import os

import numpy as np

TESTS = ("reconstruction", "closure+", "closurex")
GRID = [(25, [("emb_c2", 2), ("emb_c4", 4), ("emb_c6", 6), (("main_s0", "main_s1", "main_s2"), 10), ("emb_c16", 16)]),
        (50, [(f"len_n50_c{c}", c) for c in (2, 4, 6, 10)]),
        (100, [(f"len_n100_c{c}", c) for c in (2, 4, 6, 10)]),
        (200, [(f"len_n200_c{c}", c) for c in (2, 4, 6, 10)])]
EXTRA = [("full_no_length_mix", r"\quad $c=10$, no uniform lengths"),
         ("full_no_targeted", r"\quad $c=10$, no targeted pairs")]


def load(runs_dir, run):
    p = os.path.join(runs_dir, run, "lengths_parts.json")
    if not os.path.exists(p):
        return None
    d = json.load(open(p))
    for t in d["tests"].values():
        for k in t:
            t[k] = np.array(t[k])
    return d


def region_em(d, key, region):
    """Exact match (%) of one test in a region: 'in' (both parts within the training lengths, at most N digits),
    'out' (a longer part, at most N digits), 'beyond' (more than N digits)."""
    t, N, h = d["tests"][key], d["n_digits"], d["max_part_trained"]
    longest = np.maximum(t["n_int"], t["n_frac"])
    m = {"in": (t["total"] <= N) & (longest <= h), "out": (t["total"] <= N) & (longest > h), "beyond": t["total"] > N}[region]
    return 100.0 * float(t["ok"][m].mean()) if m.any() else None


def cell(runs_dir, runs, key, region):
    runs = (runs,) if isinstance(runs, str) else runs
    v = [region_em(d, key, region) for d in (load(runs_dir, r) for r in runs) if d]
    v = [x for x in v if x is not None]
    return float(np.mean(v)) if v else None


def f1(v):
    return "--" if v is None else ("100" if v >= 99.995 else f"{v:.2f}" if v >= 99 else f"{v:.1f}")


def table_lengthdim(runs_dir, out, csvdir, write, write_csv):
    rows, csv_rows = [], []

    def row(label, runs, N, c):
        vals = [cell(runs_dir, runs, k, reg) for reg in ("in", "out", "beyond") for k in TESTS]
        if all(v is None for v in vals):
            return False
        d = (2 * N + 2) * c
        rows.append(f"{label} & {d} & " + " & ".join(f1(v) for v in vals) + r" \\")
        csv_rows.append([N, c, d, "+".join((runs,) if isinstance(runs, str) else runs)] + vals)
        return True

    for N, cells in GRID:
        first = True
        for runs, c in cells:
            label = (rf"${N}$" if first else "") + rf" & ${c}$"
            if row(label, runs, N, c):
                first = False
            elif N > 25:
                rows.append((rf"${N}$" if first else "") + rf" & ${c}$ & {(2 * N + 2) * c} & \multicolumn{{9}}{{c}}{{training not finished}} \\")
                first = False
        if N == 25:
            for run, lab in EXTRA:
                vals = [cell(runs_dir, run, k, reg) for reg in ("in", "out", "beyond") for k in TESTS]
                if any(v is not None for v in vals):
                    rows.append(rf"\multicolumn{{3}}{{@{{}}l}}{{{lab}}} & " + " & ".join(f1(v) for v in vals) + r" \\")
                    csv_rows.append([N, 10, 520, run] + vals)
        if N != GRID[-1][0]:
            rows.append(r"\midrule")
    tex = r"""% generated by paper/make_tables.py (length_tables.py) -- do not edit
\begin{table}[pos=htbp]
	\centering
	\caption{Number length and embedding dimension: exact match (\%, length-free decoding) by the shape of the number that the decoder has to produce (the number itself for reconstruction, the result for the closure tests; items of Figures~\ref{fig:lengths} and~\ref{fig:lengthdim}). ``Within'': integer and fractional part within the training lengths (at most 12 digits each for $N=25$ and $\lfloor N/2\rfloor$ otherwise) and at most $N$ digits in total; ``longer part'': a longer part, at most $N$ digits; ``more than $N$ digits'': outside $\mathbb{D}_N$. $N=25$, $c=10$: mean of the three seeds; all other rows: one run.}
	\label{tab:lengthdim}
	\renewcommand{\arraystretch}{1.08}
	\footnotesize
	\begin{tabular}{@{}rrr@{\hskip 10pt}ccc@{\hskip 10pt}ccc@{\hskip 10pt}ccc@{}}
		\toprule
		 & & & \multicolumn{3}{c}{\textbf{Within the training lengths}} & \multicolumn{3}{c}{\textbf{Longer part}} & \multicolumn{3}{c}{\textbf{More than $N$ digits}} \\
		\cmidrule(lr){4-6} \cmidrule(lr){7-9} \cmidrule(l){10-12}
		$N$ & $c$ & $d$ & Rec. & $\dot{+}$ & $\dot{\times}$ & Rec. & $\dot{+}$ & $\dot{\times}$ & Rec. & $\dot{+}$ & $\dot{\times}$ \\
		\midrule
ROWS
		\bottomrule
	\end{tabular}
\end{table}
""".replace("ROWS", "\n".join("\t\t" + r for r in rows))
    write(os.path.join(out, "tab_lengthdim.tex"), tex)
    write_csv(os.path.join(csvdir, "length_dimension.csv"), csv_rows,
              ["N", "c", "d", "runs"] + [f"{reg}_{k}" for reg in ("within", "longer_part", "beyond_N") for k in TESTS])


def length_macros(runs_dir, fmt, TBD):
    """\\len<Run><Region><Test> for the N = 25 models used in the text, and summaries of the grid."""
    lines = [r"% length analyses (length_assets.py): exact match (%) by the shape of the number to decode"]
    main = ("main_s0", "main_s1", "main_s2")
    for runs, rname in ((main, "Main"), ("full_no_length_mix", "NoMix"), ("full_no_targeted", "NoTargeted")):
        for reg, gname in (("in", "In"), ("out", "Out"), ("beyond", "Beyond")):
            for key, tname in zip(TESTS, ("Rec", "Add", "Mul")):
                v = cell(runs_dir, runs, key, reg)
                lines.append(rf"\providecommand{{\len{rname}{gname}{tname}}}{{{fmt(v) if v is not None else TBD}}}")
    worst = lambda runs, reg: (lambda v: min(v) if all(x is not None for x in v) else None)(
        [cell(runs_dir, runs, k, reg) for k in TESTS])
    done = [(N, c, worst(runs, "in")) for N, cells in GRID for runs, c in cells]
    ok = [w for N, c, w in done if c >= 4 and w is not None]
    two = [w for N, c, w in done if c == 2 and w is not None]
    lines.append(rf"\providecommand{{\ldInMin}}{{{fmt(min(ok)) if ok else TBD}}}")       # worst cell with c >= 4
    lines.append(rf"\providecommand{{\ldTwoMax}}{{{fmt(max(two), None, 1) if two else TBD}}}")  # best cell with c = 2
    # every cell of the grid with N > 25: \ld<Region><Test><N><c>, e.g. \ldOutRecTwoHundredFour
    nname = {50: "Fifty", 100: "Hundred", 200: "TwoHundred"}
    cname = {2: "Two", 4: "Four", 6: "Six", 10: "Ten"}
    for N, cells in GRID:
        if N not in nname:
            continue
        for runs, c in cells:
            for reg, gname in (("in", "In"), ("out", "Out"), ("beyond", "Beyond")):
                for key, tname in zip(TESTS, ("Rec", "Add", "Mul")):
                    v = cell(runs_dir, runs, key, reg)
                    lines.append(rf"\providecommand{{\ld{gname}{tname}{nname[N]}{cname[c]}}}{{{fmt(v, None, 1) if v is not None else TBD}}}")
    return lines


def extra_macros(analysis_dir, fmt, TBD):
    """Macros of analysis/extra.py / analysis/digit_code.py (results/analysis/extra.json): inverse test and slot window,
    kinds of errors beyond the training lengths, decoding with the true length, Fourier analysis of the digit code."""
    p = os.path.join(analysis_dir, "extra.json")
    X = json.load(open(p)) if os.path.exists(p) else {}
    main = [X[r] for r in ("main_s0", "main_s1", "main_s2") if r in X]
    lines = [r"% further analyses (analysis/extra.py, analysis/digit_code.py)"]

    def put(name, v, digits=2):
        lines.append(rf"\providecommand{{\{name}}}{{{fmt(v, None, digits) if v is not None else TBD}}}")

    mean = lambda v: float(np.mean(v)) if len(v) else None
    inv = [m["inverse"] for m in main if "inverse" in m]
    put("invInside", mean([i["em_inside_window"] for i in inv]))                       # units whose columns fit the window
    put("invOutside", mean([i["em_outside_window"] for i in inv]))
    put("invNInside", inv[0]["n_inside"] if inv else None, 0)
    put("invNOutside", inv[0]["n_outside"] if inv else None, 0)
    put("invCeiling", 100.0 * inv[0]["n_inside"] / inv[0]["n"] if inv else None)          # exact arithmetic in the window
    wide = [m["inverse"]["em"] for m in X.values() if m.get("n_digits", 25) > 25 and m.get("c", 0) >= 4 and "inverse" in m]
    put("invWideMin", min(wide) if wide else None)
    put("invWideModels", len(wide) if wide else None, 0)
    for lo, hi, name in ((26, 100, "Hundred"), (101, 200, "TwoHundred")):                # N = 50, 100 and N = 200
        w = [m["inverse"]["em"] for m in X.values() if lo <= m.get("n_digits", 25) <= hi and m.get("c", 0) >= 4 and "inverse" in m]
        put(f"invWide{name}Min", min(w) if w else None)
        put(f"invWide{name}Max", max(w) if w else None)
        put(f"invWide{name}Models", len(w) if w else None, 0)
    for reg, name in (("out", "Out"), ("beyond", "Beyond")):                             # pooled over the seeds
        e = [m["errors"]["regions"][reg] for m in main if "errors" in m]
        tot = sum(a["errors"] for a in e)
        put(f"errLength{name}", 100.0 * sum(a["wrong_length"] for a in e) / tot if tot else None, 1)
        o = [m["oracle"][reg] for m in main if "oracle" in m]
        put(f"orcFree{name}", mean([a["em_length_free"] for a in o]), 1)
        put(f"orcTrue{name}", mean([a["em_oracle"] for a in o]), 1)
    o100 = X.get("len_n100_c4", {}).get("oracle", {}).get("out")                         # N = 100, c = 4, longer part
    put("orcFreeOutHundred", o100["em_length_free"] if o100 else None, 1)
    put("orcTrueOutHundred", o100["em_oracle"] if o100 else None, 1)
    o200 = X.get("len_n200_c4", {}).get("oracle", {}).get("out")                         # N = 200, c = 4, longer part
    put("orcFreeOutTwoHundred", o200["em_length_free"] if o200 else None, 1)
    put("orcTrueOutTwoHundred", o200["em_oracle"] if o200 else None, 1)
    f = [m["fourier"] for m in main if "fourier" in m]
    low = [100 * (h["harmonic_share"][0] + h["harmonic_share"][1]) for h in f]
    put("codeLowMin", min(low) if low else None, 0)
    put("codeLowMax", max(low) if low else None, 0)
    put("codeFirstSel", 100 * X["main_s0"]["fourier"]["harmonic_share"][0] if "fourier" in X.get("main_s0", {}) else None, 0)
    put("codeDimMin", min(h["code_dimension"] for h in f) if f else None, 1)
    put("codeDimMax", max(h["code_dimension"] for h in f) if f else None, 1)
    put("codeCosMin", min(h["between_exponent_cosine_min"] for h in f) if f else None, 2)
    put("codeWithinMax", max(100 * h["within_over_between"] for h in f) if f else None, 2)
    two = X.get("emb_c2", {}).get("fourier")
    put("codeDimCTwo", two["code_dimension"] if two else None, 1)
    put("codeCosCTwo", two["between_exponent_cosine_min"] if two else None, 2)
    dense = X.get("full_dense_ops", {}).get("fourier")
    put("codeCosDense", dense["between_exponent_cosine_min"] if dense else None, 2)
    return lines
