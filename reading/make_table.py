r"""Table 6 and the macros of the reading experiment.

    python reading/make_table.py [--runs reading/logs] [--out paper/generated]

Reads the last line of reading/logs/<condition>_s<seed>.log and writes
    <out>/tab_reader.tex          the table (one seed: the value; several seeds: mean +- SD)
    <out>/reader_numbers.tex      \newcommand macros for the numbers quoted in the text
    results/csv/reader.csv        the same numbers
"""
import argparse
import csv
import glob
import json
import os
import statistics

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))   # the repository root
ROWS = [("text_lsb", "Digit tokens only", "Text"),
        ("read_onehot", "+ one-hot digits, read place by place", "Hot"),
        ("read_f64fone", "+ FoNE (float64), read place by place", "Fsf"),
        ("read_fone", "+ FoNE (exact), read place by place", "Fone"),
        ("read_nif", "+ NIF (ours), read place by place", "Nif")]
LENGTHS = ["4", "8", "12", "14", "16", "20"]
WORD = {"4": "Four", "8": "Eight", "12": "Twelve", "14": "Fourteen", "16": "Sixteen", "20": "Twenty"}
TRAIN_MAX = 12


def last_record(path):
    rec = None
    for line in open(path, encoding="utf-8"):
        line = line.strip()
        if line.startswith("{"):
            rec = json.loads(line)
    return rec


def collect(runs):
    """{condition: {seed: record of the last step}}."""
    out = {}
    for cond, _, _ in ROWS:
        for path in sorted(glob.glob(os.path.join(runs, cond + "_s*.log"))):
            rec = last_record(path)
            if rec is not None:
                out.setdefault(cond, {})[rec["seed"]] = rec
    return out


def cell(vals):
    if len(vals) == 1:
        return f"{vals[0]:.1f}"
    return f"{statistics.mean(vals):.1f}\\,$\\pm$\\,{statistics.stdev(vals):.1f}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--runs", default=os.path.join(HERE, "reading", "logs"))
    ap.add_argument("--out", default=os.path.join(HERE, "paper", "generated"))
    args = ap.parse_args()
    data = collect(args.runs)
    missing = [c for c, _, _ in ROWS if c not in data]
    if missing:
        raise SystemExit(f"no finished run for: {missing}")
    seeds = sorted(set.intersection(*[set(v) for v in data.values()]))          # seeds that every condition has
    steps = {data[c][s]["step"] for c in data for s in seeds}
    if len(steps) != 1:
        raise SystemExit(f"the runs have different numbers of steps: {steps}")
    steps = steps.pop()
    stat = "one run" if len(seeds) == 1 else f"mean $\\pm$ SD over {len(seeds)} seeds"

    body, table = [], []
    for cond, name, _ in ROWS:
        vals = {L: [data[cond][s]["acc"][L] for s in seeds] for L in LENGTHS}
        body.append("\t\t" + name + " & " + " & ".join(cell(vals[L]) for L in LENGTHS) + r" \\")
        table.append([cond] + [f"{statistics.mean(vals[L]):.2f}" for L in LENGTHS]
                     + [f"{statistics.stdev(vals[L]):.2f}" if len(seeds) > 1 else "" for L in LENGTHS])
    n_in = sum(int(L) <= TRAIN_MAX for L in LENGTHS)
    tex = rf"""% generated by reading/make_table.py -- do not edit
\begin{{table}}[pos=htbp]
	\centering
	\caption{{Exact match (\%) of a Transformer that adds and subtracts integers, by the number of digits of the longer operand; the training operands have at most {TRAIN_MAX} digits. The number vectors are read place by place (Section~\ref{{subsubsec:reader}}); 200 test problems per length, {stat}.}}
	\label{{tab:reader}}
	\renewcommand{{\arraystretch}}{{1.08}}
	\footnotesize
	\begin{{tabular}}{{@{{}}l{"c" * len(LENGTHS)}@{{}}}}
		\toprule
		& \multicolumn{{{n_in}}}{{c}}{{\textbf{{Training lengths}}}} & \multicolumn{{{len(LENGTHS) - n_in}}}{{c}}{{\textbf{{Longer than in training}}}} \\
		\cmidrule(lr){{2-{n_in + 1}}} \cmidrule(lr){{{n_in + 2}-{len(LENGTHS) + 1}}}
		\textbf{{Input of the model}} & {" & ".join(LENGTHS)} \\
		\midrule
{chr(10).join(body)}
		\bottomrule
	\end{{tabular}}
\end{{table}}
"""
    os.makedirs(args.out, exist_ok=True)
    with open(os.path.join(args.out, "tab_reader.tex"), "w", encoding="utf-8", newline="\n") as f:
        f.write(tex)

    lines = ["% generated by reading/make_table.py -- do not edit",
             rf"\newcommand{{\rdSteps}}{{{steps}}}", rf"\newcommand{{\rdTrainMax}}{{{TRAIN_MAX}}}"]
    for cond, _, tag in ROWS:
        for L in LENGTHS:
            v = statistics.mean(data[cond][s]["acc"][L] for s in seeds)
            lines.append(rf"\newcommand{{\rd{tag}{WORD[L]}}}{{{v:.1f}}}")
    with open(os.path.join(args.out, "reader_numbers.tex"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")

    os.makedirs(os.path.join(HERE, "results", "csv"), exist_ok=True)
    with open(os.path.join(HERE, "results", "csv", "reader.csv"), "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["condition"] + [f"em_{L}" for L in LENGTHS] + [f"sd_{L}" for L in LENGTHS])
        w.writerows(table)
    print(f"seeds {seeds}, {steps} steps -> tab_reader.tex, reader_numbers.tex, results/csv/reader.csv")
    for row in table:
        print("  ", row[0].ljust(14), " ".join(x.rjust(6) for x in row[1:1 + len(LENGTHS)]))


if __name__ == "__main__":
    main()
